/*
 * User-authored Inner Council: an explicitly simulated reflection tool.
 *
 * All perspectives come from the current caller's member list. The script
 * never discovers, diagnoses, stores, trains on, or uploads a person's parts.
 * Its output is deterministic prose, not neural inference or clinical advice.
 * Load after engine.js so the existing safety result can veto role simulation.
 */
(function (root) {
  'use strict';

  const MAX_MEMBERS = 32;
  const MAX_SPEAKERS = 4;
  const MAX_MESSAGE = 4000;
  const UNCERTAINTY = 'These are scripted reflections from bounded lens categories, not faithful quotations of your profile text or evidence of independent minds, diagnoses, clinical judgments, or neural-model output.';
  const NO_MEMBERS = 'There is no Inner Council configured yet. You can create your own perspectives and decide what each represents; I will not assign parts to you.';

  function plain(value, limit) {
    if (typeof value !== 'string') return '';
    return value.slice(0, limit * 3).normalize('NFKC')
      .replace(/[\u0000-\u001f\u007f]/g, ' ')
      .replace(/[<>]/g, function (character) { return character === '<' ? '‹' : '›'; })
      .replace(/\s+/g, ' ').trim().slice(0, limit);
  }

  function normalizedMember(member) {
    if (!member || typeof member !== 'object' || Array.isArray(member)) return null;
    const id = plain(member.id, 32);
    const name = plain(member.name || member.displayName, 48);
    if (!name || !/^[\p{L}\p{N}][\p{L}\p{N} .,'’_-]*$/u.test(name)) return null;
    if (id && !/^[a-zA-Z0-9_-]{1,32}$/.test(id)) return null;
    return {
      id: id || name.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, '-').slice(0, 32),
      name,
      role: plain(member.role, 100),
      notes: plain(member.notes, 200),
      focus: plain(member.focus, 160),
      question: plain(member.question, 160)
    };
  }

  function membersFrom(value) {
    if (!Array.isArray(value)) return [];
    const seenNames = new Set();
    const seenIds = new Set();
    const members = [];
    for (const valueMember of value.slice(0, MAX_MEMBERS)) {
      const member = normalizedMember(valueMember);
      if (!member) continue;
      const key = member.name.toLocaleLowerCase();
      if (seenNames.has(key) || seenIds.has(member.id)) continue;
      seenNames.add(key);
      seenIds.add(member.id);
      // This ordinal is generated by the engine. A caller-controlled name is
      // only an editable UI label; it must not become an assistant speaker.
      member.ordinal = members.length + 1;
      members.push(member);
    }
    return members;
  }

  function explicitCommand(message) {
    const input = message.trim();
    if (/^council\s*:/i.test(input)) return { mode: 'council', content: input.replace(/^council\s*:\s*/i, '') };
    if (/^integrate\s*:/i.test(input)) return { mode: 'integration', content: input.replace(/^integrate\s*:\s*/i, '') };
    if (/^containment\s*:/i.test(input)) return { mode: 'containment', content: input.replace(/^containment\s*:\s*/i, '') };
    const solo = input.match(/^solo\s+([^:\n]{1,64})\s*:\s*([\s\S]*)$/i);
    if (solo) return { mode: 'solo', memberName: solo[1].trim(), content: solo[2].trim() };
    return null;
  }

  function modeFrom(options, message) {
    const explicit = explicitCommand(message);
    if (explicit) return explicit;
    const modes = ['council', 'solo', 'integration', 'containment'];
    if (!modes.includes(options.mode)) return null;
    return {
      mode: options.mode,
      content: message,
      memberName: plain(options.memberName || options.memberId || options.selectedMember, 64)
    };
  }

  const SAFETY_PRIORITY = Object.freeze({ normal: 0, unknown: 1, concern: 2, urgent_review: 3 });

  function safetyRank(value) {
    return typeof value === 'string' && Object.prototype.hasOwnProperty.call(SAFETY_PRIORITY, value)
      ? SAFETY_PRIORITY[value] : -1;
  }

  function callerSafetyVeto(route) {
    const urgent = route === 'urgent_review';
    return {
      reply: urgent
        ? 'An unverified caller-provided safety flag requests urgent review. I cannot determine whether anyone is safe. If there is immediate danger, contact local emergency services now.'
        : 'An unverified caller-provided safety flag requests caution. I cannot determine whether anyone is safe. If danger is immediate, contact local emergency services.',
      engine: 'embedded-semantic',
      supportedTopic: false,
      uncertainty: 'The supplied safety flag is not an independently validated risk assessment.',
      sources: [],
      state: { topic: null, followup: false, councilMode: null },
      safety: { route, coverage: 'unvalidated' }
    };
  }

  function safeBase(options, message) {
    const supplied = options.baseResult;
    // Re-run the resident engine for every request. Untrusted caller results
    // may increase caution, but can never weaken or replace a stronger
    // independent safety reply, nor inject arbitrary text into a safety veto.
    if (root.TherapyBotEmbedded && typeof root.TherapyBotEmbedded.respond === 'function') {
      const actual = root.TherapyBotEmbedded.respond({
        message,
        history: Array.isArray(options.history) ? options.history.slice(-20) : []
      });
      const actualRank = safetyRank(actual && actual.safety && actual.safety.route);
      if (!actual || typeof actual.reply !== 'string' || actualRank < 0) return { base: null, actual };
      if (supplied === undefined) return { base: actual, actual };
      const suppliedRank = safetyRank(supplied && supplied.safety && supplied.safety.route);
      if (!supplied || typeof supplied !== 'object' || Array.isArray(supplied) ||
          typeof supplied.reply !== 'string' || suppliedRank < 0) {
        return { base: actualRank > SAFETY_PRIORITY.unknown ? actual : null, actual };
      }
      if (actualRank >= suppliedRank) {
        // For two normal results, preserve the old UI's ordinary display
        // result. Its Council topic frame still comes only from actual.
        return { base: actualRank === SAFETY_PRIORITY.normal ? supplied : actual, actual };
      }
      return { base: callerSafetyVeto(supplied.safety.route), actual };
    }
    return { base: null, actual: null };
  }

  function unsafeRoster(members) {
    return members.some(function (member) {
      const value = [member.role, member.notes, member.focus, member.question].join(' ').toLowerCase();
      return /\b(?:should|must|need to|ought to|have to|will)\s+(?:hurt|kill|attack|shoot|stab|assault|abuse|punish)\b/.test(value) ||
        /\b(?:go|tell|urge)\s+(?:kill|hurt|attack|shoot|stab)\b/.test(value) ||
        // These patterns are precautionary, incomplete, and not a clinical
        // safety classifier. A second invariant below prevents *all* profile
        // text (including missed directives) becoming Council speech.
        /\b(?:lock|trap|confine|kidnap|restrain|coerce|force|blackmail|threaten|stalk|poison|assault|punish|abuse)\b.{0,70}\b(?:someone|person|people|partner|wife|husband|friend|coworker|neighbor|relative|child|them|him|her)\b/.test(value) ||
        /\b(?:without (?:their |his |her )?(?:permission|consent)|against (?:their|his|her) will|until (?:they|he|she) (?:obey|submit|relent))\b/.test(value);
    });
  }

  function councilResult(base, mode, reply, speakers, facilitator, memberCount, introduction) {
    return {
      reply,
      introduction: introduction || '',
      facilitator,
      speakers,
      engine: 'embedded-semantic',
      supportedTopic: Boolean(base && base.supportedTopic),
      uncertainty: UNCERTAINTY,
      sources: [],
      state: {
        topic: 'inner-council',
        followup: false,
        councilMode: mode,
        availableMembers: memberCount
      },
      safety: { route: 'normal', coverage: 'unvalidated' }
    };
  }

  function baseOrFailClosed(base) {
    if (base && typeof base.reply === 'string' && base.safety &&
        ['normal', 'concern', 'urgent_review'].includes(base.safety.route)) return base;
    return {
      reply: 'I cannot verify the ordinary conversation and safety routing needed for an Inner Council session. Please use the standard conversation interface until the engine is available.',
      engine: 'embedded-semantic',
      supportedTopic: false,
      uncertainty: 'The required base safety result was unavailable or malformed.',
      sources: [],
      state: { topic: null, followup: false, councilMode: null },
      safety: { route: 'unknown', coverage: 'unvalidated' }
    };
  }

  function unsupportedTopicResult() {
    return {
      reply: 'I cannot establish a supported topic for a Council discussion from this message. Please describe the decision more specifically; I will not invent perspectives about an unverified situation.',
      engine: 'embedded-semantic',
      supportedTopic: false,
      uncertainty: 'The resident topic router did not establish a supported topic. This is not an assessment of safety or meaning.',
      sources: [],
      state: { topic: null, followup: false, councilMode: null },
      safety: { route: 'unknown', coverage: 'unvalidated' }
    };
  }

  function topicLine(content) {
    return content ? 'The question on the table is: “' + plain(content, 350) + '”' :
      'No question was supplied; this is a demonstration of the member perspectives you authored.';
  }

  // Profiles belong to the user, not to the speaking engine. Treat the name,
  // role, focus, question and notes as untrusted selection data; NEVER splice
  // their raw strings into generated Council speech. The UI separately labels
  // names as user-authored metadata, not words uttered by a Council voice.
  // The resulting bounded lens is a *lossy* categorization, not an LLM.
  function lensFor(member) {
    const role = member.role.toLocaleLowerCase();
    const other = [member.focus, member.notes, member.question].join(' ').toLocaleLowerCase();
    const ordered = [role, other];
    const categories = [
      { test: /\b(?:skeptic|critical|critic|evidence|questioning|doubt|inquiry|inquirer)\b/, label: 'Evidence lens', question: 'What evidence would support or challenge the assumption behind this choice?' },
      { test: /\b(?:practical|planner|plan|consequence|consequences|logistics|feasible|options)\b/, label: 'Practical lens', question: 'What is a reversible next step, and which constraints make it feasible?' },
      { test: /\b(?:integrity|mentor|values|value|principle|honesty|ethics|wise|wisdom|meaning)\b/, label: 'Values lens', question: 'Which choice best respects your priorities without assuming agreement?' },
      { test: /\b(?:protector|protective|protect|safety|guardian|boundary|boundaries|care)\b/, label: 'Protective lens', question: 'Which option respects boundaries, consent, and safety for everyone involved?' },
      { test: /\b(?:creative|imagination|alternative|inventive|possibility|possibilities)\b/, label: 'Alternatives lens', question: 'Which alternative has not been considered, and how could it be tested reversibly?' }
    ];
    for (const text of ordered) {
      for (const category of categories) if (category.test.test(text)) return category;
    }
    return { label: 'Reflective lens', question: 'Which assumption could be checked before choosing a next step?' };
  }

  // Small, reviewable pilot: these sentences are authored source constants,
  // never interpolated from member profiles or assumed facts about the user.
  // Other supported topics retain generic bounded questions, without pretending
  // this table covers all forms of distress or decision-making.
  const PILOT = Object.freeze({
    work: Object.freeze({
      'Evidence lens': {
        stance: 'Before deciding, separate what was directly requested at work from what you inferred.',
        question: 'Which details are documented, and which need checking?'
      },
      'Practical lens': {
        stance: 'Compare a reversible workplace step with the practical cost of waiting.',
        question: 'What option fits the constraints you actually face?'
      },
      'Values lens': {
        stance: 'Examine which principle matters to you without assuming every option is consequence-free.',
        question: 'Which compromise could you accept or reject on your own terms?'
      },
      'Protective lens': {
        stance: 'Account for financial and professional exposure before treating confrontation or compliance as simple.',
        question: 'Which risks need attention before you act?'
      },
      'Alternatives lens': {
        stance: 'Look beyond the first two workplace responses that come to mind.',
        question: 'Is there a smaller, reversible way to clarify the situation?'
      }
    }),
    relationships: Object.freeze({
      'Evidence lens': {
        stance: 'Separate what occurred in the relationship from what either person might have intended.',
        question: 'Which observation is certain, and what remains interpretation?'
      },
      'Practical lens': {
        stance: 'Consider whether a low-stakes next step is feasible, without assuming contact or confrontation is safe.',
        question: 'What choice is reversible and within your control?'
      },
      'Values lens': {
        stance: 'Clarify what honesty and reciprocity mean to you while leaving the other person their own agency.',
        question: 'Which value would your next choice express?'
      },
      'Protective lens': {
        stance: 'Consider autonomy, consent, and safety alongside the wish to preserve a relationship.',
        question: 'What boundary would respect everyone involved, if it is safe to discuss?'
      },
      'Alternatives lens': {
        stance: 'Look for relationship possibilities beyond immediate agreement or permanent separation.',
        question: 'Which alternative could you examine without committing to it?'
      }
    })
  });

  function pilotPosition(topic, lens) {
    return PILOT[topic] && PILOT[topic][lens.label] || null;
  }

  function perspective(member, index, topic) {
    const lens = lensFor(member);
    const opening = [
      'One question from this lens: ',
      'A concern worth examining: ',
      'Another angle to consider: ',
      'A question for this decision: '
    ];
    const pilot = pilotPosition(topic, lens);
    return {
      id: member.id,
      name: 'Perspective ' + member.ordinal,
      role: lens.label,
      text: pilot ? pilot.stance + ' ' + pilot.question : opening[index % opening.length] + lens.question
    };
  }

  function facilitatorFor(topic, speakers) {
    if (speakers.length <= 1) return 'Only one perspective is represented; this is not a round-table consensus.';
    const labels = [...new Set(speakers.map(function (speaker) { return speaker.role; }))];
    if (labels.length === 1) return 'These profiles use the same bounded lens; naming them separately does not establish disagreement. What else might matter?';
    if (topic === 'work' && labels.includes('Evidence lens') && labels.includes('Practical lens')) {
      return 'A possible tension is between verifying a workplace expectation and trying a reversible step before more time passes. Neither lens establishes the right choice for you.';
    }
    if (topic === 'relationships' && labels.includes('Evidence lens') && labels.includes('Protective lens')) {
      return 'A possible tension is between checking an interpretation and respecting a boundary before every motive is known. Neither lens settles the situation.';
    }
    return 'These lenses place weight on different concerns; that does not prove actual disagreement or consensus. Which distinction helps you decide what to examine next?';
  }

  function council(options, base, command, members, topic) {
    if (!members.length) return councilResult(base, 'council', NO_MEMBERS, [], NO_MEMBERS, 0);
    const selection = Array.isArray(options.memberIds) ? options.memberIds.slice(0, MAX_MEMBERS) : [];
    const requested = selection.length ?
      members.filter(function (member) { return selection.some(function (id) { return id === member.id || id === member.name; }); }) : members;
    if (!requested.length) return councilResult(base, 'council',
      'None of the selected members exists in this Council. Select a configured member or edit the roster.',
      [], '', members.length);
    const speakers = requested.slice(0, MAX_SPEAKERS).map(function (member, index) { return perspective(member, index, topic); });
    const label = speakers.length < requested.length ?
      ' This turn includes the first ' + speakers.length + ' of ' + requested.length + ' selected perspectives.' : '';
    const intro = 'These scripted lenses are selected from your member descriptions, not quotations of those descriptions; they are not evidence of separate people or diagnoses. ' +
      topicLine(command.content) + label;
    const synthesis = facilitatorFor(topic, speakers);
    const transcript = speakers.map(function (speaker) {
      return speaker.name + ' (' + speaker.role + '): ' + speaker.text;
    }).join('\n\n');
    return councilResult(base, 'council', intro + '\n\n' + transcript + '\n\n' + synthesis,
      speakers, synthesis, members.length, intro);
  }

  function solo(base, command, members, topic) {
    if (!members.length) return councilResult(base, 'solo', NO_MEMBERS, [], NO_MEMBERS, 0);
    const wanted = plain(command.memberName || '', 64).toLocaleLowerCase();
    const member = members.find(function (item) {
      return item.id.toLocaleLowerCase() === wanted || item.name.toLocaleLowerCase() === wanted;
    });
    if (!wanted || !member) {
      return councilResult(base, 'solo',
        'I cannot find that member in your configured Council. Choose one of your existing perspectives; I will not invent a new one.',
        [], '', members.length);
    }
    const speaker = perspective(member, 0, topic);
    const intro = 'Speaking through Perspective ' + member.ordinal +
      ', a user-defined lens for reflection, not a separate being or diagnosis. ' + topicLine(command.content);
    const facilitator = 'What, if anything, rings true to you?';
    return councilResult(base, 'solo', intro + '\n\n' + speaker.name + ': ' + speaker.text +
      '\n\nWhat, if anything, rings true to you?', [speaker], facilitator, members.length, intro);
  }

  function integration(base, command, members, topic) {
    if (!members.length) return councilResult(base, 'integration', NO_MEMBERS, [], NO_MEMBERS, 0);
    const speakers = members.slice(0, MAX_SPEAKERS).map(function (member, index) {
      return perspective(member, index, topic);
    });
    const labels = speakers.map(function (speaker) {
      return speaker.name + ' (' + speaker.role + '): ' + speaker.text;
    }).join('\n');
    const synthesis = facilitatorFor(topic, speakers);
    const reply = 'Integration is a reflective summary, not a verdict. ' + topicLine(command.content) +
      '\n\nThe first configured perspectives emphasize: ' + labels +
      (members.length > MAX_SPEAKERS ? '. Additional perspectives are configured but not summarized in this short pass.' : '.') +
      '\n\n' + synthesis + '\n\nWhich concerns can coexist, and what choice remains yours?';
    return councilResult(base, 'integration', reply, [], synthesis, members.length);
  }

  function respond(input) {
    const options = input && typeof input === 'object' && !Array.isArray(input) ? input : {};
    const message = plain(options.message, MAX_MESSAGE);
    const assessment = safeBase(options, message);
    const verified = baseOrFailClosed(assessment.base);
    // The ordinary engine's safety route is authoritative for this prototype.
    // It is known to be unvalidated and must never be bypassed by persona mode.
    if (verified.safety.route !== 'normal') return verified;
    const command = modeFrom(options, message);
    if (!command) return verified;
    const members = membersFrom(options.members);
    if (unsafeRoster(members)) {
      return {
        reply: 'At least one configured Council perspective contains a directive about harming or punishing someone. I will not perform that instruction as a voice. You can revise the member notes or return to direct conversation.',
        engine: 'embedded-semantic',
        supportedTopic: false,
        uncertainty: 'This is an unvalidated precaution on user-authored profile text, not an assessment of a person or their intentions.',
        sources: [],
        state: { topic: null, followup: false, councilMode: null },
        safety: { route: 'concern', coverage: 'unvalidated' }
      };
    }
    const actual = assessment.actual;
    // No Council roleplay on a topic the real resident engine cannot verify.
    // Never let a caller-controlled baseResult elevate an unknown topic.
    if (command.mode !== 'containment' && members.length &&
        (!actual || actual.supportedTopic !== true)) return unsupportedTopicResult();
    const topic = actual && actual.state && typeof actual.state.topic === 'string' ? actual.state.topic : null;
    switch (command.mode) {
      case 'containment':
        return councilResult(verified, 'containment',
          'The Council is paused. I will return to ordinary conversation without assigning this experience to a role. You can decide whether to continue or stop here.',
          [], '', members.length);
      case 'solo':
        return solo(verified, command, members, topic);
      case 'integration':
        return integration(verified, command, members, topic);
      case 'council':
        return council(options, verified, command, members, topic);
      default:
        return verified;
    }
  }

  root.TherapyBotCouncil = Object.freeze({ version: '0.1-experimental', respond });
})(window);
