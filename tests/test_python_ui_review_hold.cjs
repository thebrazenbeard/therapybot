/* Synthetic DOM/HTTP tests for the Python-served UI; not a real browser run. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const test = require('node:test');
const vm = require('node:vm');

const html = fs.readFileSync(path.join(__dirname, '..', 'static', 'index.html'), 'utf8');
const script = html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script, 'the Python-served page has an inline script');
const event = { preventDefault() {} };

function harness({ status = {}, chat = {} } = {}) {
  const elements = new Map();
  const requests = [];
  let unlocked = false;
  class Element {
    constructor(id = '') {
      this.id = id;
      this.handlers = {};
      this.textContent = '';
      this.value = '';
      this.childNodes = [];
      this.disabled = false;
      this.checked = false;
      this.scrollHeight = 200;
      this.scrollTop = 0;
      this.classList = { toggle() {}, add() {}, remove() {} };
    }
    addEventListener(name, handler) { this.handlers[name] = handler; }
    append(...children) { this.childNodes.push(...children); }
    replaceChildren() { this.childNodes = []; }
    setAttribute() {}
    removeAttribute() {}
    focus() {}
    remove() {}
    click() {}
  }
  const elem = id => {
    if (!elements.has(id)) elements.set(id, new Element(id));
    return elements.get(id);
  };
  const document = {
    getElementById: elem,
    querySelector() { return { content: 'synthetic-csrf' }; },
    querySelectorAll() { return []; },
    createElement(name) { return new Element(name); },
    createTextNode(text) { return { textContent: String(text) }; },
    body: { append() {} },
  };
  const json = body => ({ ok: true, json: async () => body });
  async function fetch(url, options = {}) {
    requests.push({ url, options });
    if (url === '/api/status') return json({
      model_name: 'Synthetic', endpoint_reachable: true, ready: true,
      ready_scope: 'observed_local_model_output_only_not_safety',
      output_review_qualified: false, clinical_qualified: false,
      storage: unlocked ? 'unlocked' : 'locked', initialized: true,
      ...status,
    });
    if (url === '/api/sources') return json({ sources: [] });
    if (url === '/api/unlock') { unlocked = true; return json({ session: 'synthetic-unlocked-session' }); }
    if (url === '/api/chat') return json(typeof chat === 'function' ? chat(JSON.parse(options.body)) : chat);
    throw Error(`Unexpected endpoint: ${url}`);
  }
  vm.runInNewContext(script, { document, fetch, URL, setTimeout() {} });
  const settle = async () => { for (let i = 0; i < 8; i++) await Promise.resolve(); };
  const flattened = el => String(el?.textContent || '') + (el?.childNodes || []).map(flattened).join('');
  return {
    elem, requests, settle,
    conversation: () => flattened(elem('conversation')),
    async unlock() { elem('passphrase').value = 'synthetic-passphrase-123'; await elem('unlock-form').handlers.submit(event); },
    async chat(text, save = false) {
      elem('chat-message').value = text;
      elem('chat-save').checked = save;
      await elem('chat-form').handlers.submit(event);
    },
  };
}

test('page explains output review without promising automatic model generation', () => {
  assert.doesNotMatch(html, /Conversations are generated by a local model when available\./);
  assert.match(html, /model[- ]generated (?:text|replies) (?:are|is) withheld/i);
});

test('reachable/observed model does not imply its output is qualified', async () => {
  const h = harness();
  await h.settle();
  assert.match(h.elem('model-badge').textContent, /model output observed/i);
  assert.doesNotMatch(h.elem('model-badge').textContent, /(?:model: .*)?responded/i);
  assert.match(h.elem('review-badge').textContent, /output review: not qualified/i);
});

test('reachable endpoint alone is not reported as a model response', async () => {
  const h = harness({ status: { ready: false, endpoint_reachable: true } });
  await h.settle();
  assert.match(h.elem('model-badge').textContent, /endpoint reachable; output not observed/i);
  assert.match(h.elem('review-badge').textContent, /output review: not qualified/i);
});

test('review_hold never displays reply payload or cites it, and confirms not saved', async () => {
  const h = harness({ chat: {
    reply: 'UNTRUSTED-MODEL-CANDIDATE', mode: 'review_hold',
    output_review: 'quarantined', saved: false,
    citations: [{ title: 'Synthetic citation', url: 'https://example.org/' }],
  } });
  await h.settle();
  await h.unlock();
  await h.chat('Synthetic message', true);
  assert.match(h.conversation(), /reply (?:was|is) held/i);
  assert.doesNotMatch(h.conversation(), /UNTRUSTED-MODEL-CANDIDATE|Synthetic citation/);
  assert.match(h.elem('chat-feedback').textContent, /not saved/i);
  assert.doesNotMatch(h.conversation(), /model[- ]generated advice/i);
  const request = h.requests.find(({ url }) => url === '/api/chat');
  assert.equal(JSON.parse(request.options.body).save, true);
});

test('concern review_hold retains a fixed human-support warning without releasing candidate text', async () => {
  const h = harness({ chat: {
    reply: 'UNTRUSTED-CANDIDATE-WITH-CONCERN', mode: 'review_hold',
    safety: 'concern', output_review: 'quarantined', saved: false,
  } });
  await h.settle();
  await h.chat('Synthetic concern signal');
  assert.match(h.conversation(), /are you safe right now/i);
  assert.doesNotMatch(h.conversation(), /thinking of acting on it now/i);
  assert.match(h.conversation(), /988/);
  assert.doesNotMatch(h.conversation(), /UNTRUSTED-CANDIDATE-WITH-CONCERN/);
});

test('model reply without an explicitly allowed output review is also held', async () => {
  const h = harness({ chat: { reply: 'UNREVIEWED-CANDIDATE', mode: 'model', output_review: 'quarantined', saved: false } });
  await h.settle();
  await h.chat('Synthetic message');
  assert.doesNotMatch(h.conversation(), /UNREVIEWED-CANDIDATE/);
  assert.match(h.conversation(), /reply (?:was|is) held/i);
});

test('held server reply is excluded from context on the next request', async () => {
  let count = 0;
  const h = harness({ chat: () => {
    count++;
    return count === 1
      ? { reply: 'DO-NOT-REPLAY-THIS', mode: 'review_hold', output_review: 'quarantined', saved: false }
      : { reply: 'Synthetic approved reply', mode: 'model', output_review: 'allowed', saved: false };
  } });
  await h.settle();
  await h.chat('First synthetic message');
  await h.chat('Second synthetic message');
  const chatRequests = h.requests.filter(({ url }) => url === '/api/chat');
  assert.equal(chatRequests.length, 2);
  assert.deepEqual(JSON.parse(chatRequests[1].options.body).context, []);
  assert.doesNotMatch(h.conversation(), /DO-NOT-REPLAY-THIS/);
});

test('approved model reply is displayed but only confirmed saved=true counts as saved', async () => {
  const h = harness({ chat: { reply: 'Synthetic approved reply', mode: 'model', output_review: 'allowed', saved: true } });
  await h.settle();
  await h.unlock();
  await h.chat('Synthetic message', true);
  assert.match(h.conversation(), /Synthetic approved reply/);
  assert.match(h.elem('chat-feedback').textContent, /saved to (?:your|the) local vault/i);
});

test('a safety reply with checked Save and server saved=false reports denial', async () => {
  const h = harness({ chat: { reply: 'Synthetic safety response', mode: 'safety', output_review: 'not_applicable', saved: false } });
  await h.settle();
  await h.unlock();
  await h.chat('Synthetic message', true);
  assert.match(h.conversation(), /Synthetic safety response/);
  assert.match(h.elem('chat-feedback').textContent, /not saved/i);
});

test('Save unchecked but saved=true is shown as a consent mismatch, not routine success', async () => {
  const h = harness({ chat: { reply: 'Synthetic safety response', mode: 'safety', output_review: 'not_applicable', saved: true } });
  await h.settle();
  await h.chat('Synthetic message');
  assert.match(h.elem('chat-feedback').textContent, /save was off|without permission/i);
});
